def preference(stem: str, *, strong: bool, month_zhi: str) -> list[str]:
    """某日干在给定强弱与月令下的候选取用**偏好**（有序，越靠前越优先）。

    月令覆盖若与基线首位相同则不重复；否则把覆盖五行**提到首位**，其余保持相对次序。
    """
    base = list(_BASE[stem][strong])
    override = _MONTH_OVERRIDE.get(stem, {}).get(month_zhi, {}).get(strong)
    if override and override != base[0]:
        base = [override] + [w for w in base if w != override]
    return base


def avoid(stem: str, *, strong: bool, month_zhi: str) -> list[str]:
    """该书日干在给定强弱下的**忌讳**五行（书里明文点出的「最怕/最忌」）。"""
    return list(_AVOID[stem][strong])
