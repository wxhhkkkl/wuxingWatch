# 生克权阈值（书《上》第一节 五行旺衰「生克权＝太弱以上（静态旺度≥2.4度）或有强根（≥2.4度为强根）或」 / 书《上》第一节 五行旺衰，有一个八字，您看我分析地对否？ 的「强根」）
WEAK_LINE = 2.4
STRONG_ROOT = 2.4
# 受生上限倍数（书《下》第八节 六冲/上 3859「有根无气只能接受 4 倍以下之生」）
SHENG_LIMIT_RATIO = 4.0


def has_shengke_power(*, static_deg: float, root_deg: float, has_sheng: bool) -> bool:
    """生克权 = 太弱以上（静态旺度 ≥2.4）**或**有强根（≥2.4）**或**有生（书《上》第一节 五行旺衰「生克权＝太弱以上（静态旺度≥2.4度）或有强根（≥2.4度为强根）或」）。

    **这是新书相对旧版的扩展**：旧版只说「比弱以上有生克权」；
    新版多了「有强根」与「有生」两个充分条件。
    """
    return static_deg >= WEAK_LINE or root_deg >= STRONG_ROOT or has_sheng


# 注：原 `apply_ke_with_power_check`（带生克权的相克结算，含「受克者无生克权则
# 反减半」）已删除——它**无任何调用点**（死代码），且「减半」出自《初级答疑》
# L1461-1464；书 上 971-976 只给四条**定性**性质，无数值。


def can_receive_sheng(*, sub_has_root: bool, sub_has_qi: bool, main_deg: float,
                      sub_deg: float) -> bool:
    """受生范围判定（书 上 3859、下 1584）。

    | 受生者状态 | 行为 |
    |---|---|
    | 有根有气 | 可接受 4 倍以上照常受生（4 倍上限**不适用**） |
    | 有根无气 | 超过 4 倍则**不受生** |

    **「有气」按月令状态判**，不是旺度——书 上 353：「五行在月令或大运处于
    '旺、余气、相'的状态，称为当令或有气；处于'休、囚、死'的状态，称为失令或无气」。
    故上 990 的壬水静态 **2.5 度**仍判「有根无气」、上 551 的庚金 **3 度**亦然；
    判据由 `tables.element_has_qi` 给出。

    > 2026-09-11 删除：「受生者无生克权且主生者太旺（≥26）→ 受生者反而减半」
    > 一分支无书证（其上 689 的引文实为「主生者须有生克权、受生者须在受生范围内」
    > 一句前提，两册精髓均无 5 成反减条），随 C26-9 作废删除。
    """
    if sub_has_root and sub_has_qi:
        return True
    if not sub_deg:
        return False
    return main_deg <= SHENG_LIMIT_RATIO * sub_deg


