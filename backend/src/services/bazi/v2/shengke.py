"""v2 生克层：比例增减成数、单步结算、生克权、结算顺序（012 期 US2，FR-019..022）。

书源：**《四柱精髓（上）》**——673-722（生克规则四公式）、967-990（生克权）、
742-744（成数乘自身旺度的算例）、《四柱精髓（下）》1584 与 上 3859（受生上限 4 倍）。

**本模块与旧引擎最大的差异**：增减成数**不再用固定倍率表**，改按**力量比缩放**。
旧引擎的 `_TZSG_FACTOR` 是 0.7/1.3、0.8/1.2、0.7/0.5、**0.7**/0.6 的常量表；
新书给出四个公式，且**异性相克主克方由 3 成改为 2 成**。
"""

from __future__ import annotations

# 四公式的**基数**（1:1 时的成数）。书《四柱精髓（上）》「生克规则」原文：
#
#   ① 同性相生（主生者与受生者 1:1）：主生者减力 3 成（×0.7），受生者增力 3 成（×1.3）
#        SS = 3 × (Z/S)      ZS = 3 × (S/Z)
#   ② 异性相生：主生者减力 2 成（×0.8），受生者增力 2 成（×1.2）
#        SS = 2 × (Z/S)      ZS = 2 × (S/Z)
#   ③ 同性相克：主克者减力 3 成，受克者减力 5 成（×0.5）
#        SK = 5 × (Z/S)      ZK = 3 × (S/Z)
#   ④ 异性相克：主克者减力 2 成，受克者减力 4 成（×0.6）
#        SK = 4 × (Z/S)      ZK = 2 × (S/Z)
#
#   Z＝主方旺度，S＝受方旺度；SS/SK 为受方成数，ZS/ZK 为主方成数。
#   本表的 (main, sub) 即 (ZS/ZK, SS/SK)。
#
# ⚠️ 书明文：「理论①②成立的前提是——主生者必须具有生克权、**受生者必须在受生范围内**；
#    理论③④成立的条件是——主克者必须具有生克权。」
#    见 `has_shengke_power` / `can_receive_sheng`。
BASE = {
    ("生", True):  (3.0, 3.0),
    ("生", False): (2.0, 2.0),
    ("克", True):  (3.0, 5.0),
    ("克", False): (2.0, 4.0),
}

# 成数上限：超过 10 成即归零（书「减力 10 成以上者力量尽失」）
MAX_CHENG = 10.0


def cheng(kind: str, *, same: bool, main_deg: float, sub_deg: float, party: str) -> float:
    """增/减力**成数**（Z＝主方旺度，S＝受方旺度）。

    统一形式：`成数 = 基数 × (对方旺度 ÷ 自己旺度)`
      - 受方成数 = 基数_sub × (Z/S)，即书里的 `SS`（生）与 `SK`（克）
      - 主方成数 = 基数_main × (S/Z)，即书里的 `ZS`（生）与 `ZK`（克）

    `party` ∈ {"main", "sub"}。任一方旺度为 0 时返回 0（无法比较力量比）。
    """
    base_main, base_sub = BASE[(kind, bool(same))]
    if party == "main":
        if not main_deg:
            return 0.0
        return base_main * (sub_deg / main_deg)
    if not sub_deg:
        return 0.0
    return base_sub * (main_deg / sub_deg)


def apply_change(deg: float, *, cheng: float) -> float:
    """单步结算：在**自身**旺度上按成数增减。

    书《上》第一节 五行旺衰 的算例给出决定性证据：辛金 9.75 度、损耗 0.99 成，
    「即辛金损耗 **0.97 度**」＝ 9.75 × 0.99/10 —— **成数乘的是自身旺度**。
    另有两处算例交叉验证同一口径：上 754（壬水日干静 2.8 度、寅木 8.125 倍 →
    ZS=24.375 成 → 归 0）、下 3447（乙木 12.2 度泄 1.5 成 → 10.4）。

    成数 `cheng` 为正表示增力、为负表示减力；减力达 10 成（`cheng <= -10`）
    即力量尽失归零；结果不足即归 0。
    """
    if cheng <= -MAX_CHENG:
        return 0.0
    return round(max(0.0, deg * (1.0 + cheng / 10.0)), 3)


