def test_cong_ruo_yin_joins_ji():
    """从弱：喜＝**其余克泄耗**，忌＝**生助（印、比劫）**。

    书 下 4077 是**从弱格自己那一节的取用原则**：「取克泄耗日主的五行为用神，
    **生助**日主的五行为忌神」。书里印入忌的明文另见 下 4086（该节首例「忌金水」）、
    3079、3749、3759（宋子文造「忌土金，尤忌土」）、3808（孙中山造「己土忌神」）、
    3848、4495 等 ≥10 处。

    ⚠️ **书内冲突留痕**：下 4095（乙丑 乙酉 癸酉 辛酉）把印（金）列入用、只忌比劫；
    下 4265（己丑 丙寅 己卯 丁卯）把印（火）取为首用。本实现取 下 4077 的本则
    （印入忌），下 4095/4265 两例因此**不复现**——两例的印字均与「印旺极而日主
    不受生」/调候有关，属特例；书在 下 4095 后又把火木踢出实际用神，可佐其非本则。
    """
    # 日主癸水，用神取官杀（土）→ 其余克泄耗（火＝财、木＝食伤）入喜；忌＝生助（金＝印、水＝比劫）
    xi, ji, xian = _derive("土", direction="从势", gtype="cong_ruo", dm_wx="水")
    assert set(xi) == {"木", "火"}, "其余克泄耗（食伤、财）入喜"
    assert set(ji) == {"金", "水"}, "生助（印、比劫）入忌（下 4077）"
    assert xian == []

    # 日主己土，用神火 → 喜＝其余克泄耗（木＝官杀、金＝食伤、水＝财）；忌＝生助里的比劫(土)
    # （印＝火正是用神本身，被 `w != yong` 滤掉，故忌只剩比劫）
    xi2, ji2, _ = _derive("火", direction="从势", gtype="cong_ruo", dm_wx="土")
    assert set(xi2) == {"木", "金", "水"}, "其余克泄耗入喜"
    assert ji2 == ["土"], "忌＝生助侧的比劫（印＝火即用神本身）"
    # 已知缺口（记入 notes）：书 下 4265 说「水为忌神」，而水在从弱本则下属克泄耗（财）、
    # 应入喜——该「忌」出自寒暖湿燥（寅月余寒）这第三因素，实现未落地「调候加忌」那一层。
    assert "水" in xi2, "财（水）在从弱本则下属克泄耗，入喜"


