import pytest

from services.bazi.v2 import xiyong_analysis_v2, xiyong_v2

ALL_WX = {"木", "火", "土", "金", "水"}
_KEYS = ("year", "month", "day", "time")


def _derive(yong: str, *, direction: str = "扶抑", gtype: str = "zheng",
            dm_wx: str = "木"):
    """构造只含用神与方向的 `out`，直接调 `_derive_xi_ji`（**规则表**用例）。"""
    out = {"theoretical": {"element": yong}, "practical": None, "direction": direction}
    return xiyong_v2._derive_xi_ji(out, dm_wx, gtype)


def _pillars(*gz: str) -> dict:
    """四柱（年 月 日 时）→ 引擎柱位字典。"""
    return {k: {"gan": g[0], "zhi": g[1]} for k, g in zip(_KEYS, gz)}


