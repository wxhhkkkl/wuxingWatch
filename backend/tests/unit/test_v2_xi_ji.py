def test_tier_stays_on_favorable_side_for_cong_and_hua():
    """第一/第二用神必须与喜神同侧——化格第二用神＝生助化神者；从弱第二/三用神＝其余从神。

    书 下 4112「取生助化神的五行为用神」；书 下 4095「从弱…理论上取土金火木为用，
    唯独忌水」。修复前从格一律取 `SHENG[用神]`（「喜神为其所生」——与 S1 同一误解），
    会把忌神（如从弱时的比劫）排进用神层次。

    注：从弱的第二/三用神只在**主从神同侧**（克泄耗）中按旺度排；印虽入喜神
    （下 4095），但书未给从格的用神层次次序，故不参与排序——故此处用**包含**断言。
    """
    hua = {"element": "土", "direction": "从化神", "basis": "化格：取生助化神（土）的五行为用"}
    f = {"木": 8.0, "水": 4.0, "火": 6.0, "土": 20.0, "金": 10.0}
    assert xiyong_v2._assign_tier(hua, day_master="甲", dm_wx="木", gtype="hua",
                                  final=f, month_zhi="辰") == {"first": "土", "second": "火",
                                                               "third": None}
    ruo = {"element": "土", "direction": "从势", "basis": "从弱：取所从之官杀（土）为用"}
    f2 = {"木": 3.0, "火": 2.0, "土": 5.0, "金": 30.0, "水": 1.0}
    t = xiyong_v2._assign_tier(ruo, day_master="癸", dm_wx="水", gtype="cong_ruo",
                              final=f2, month_zhi="酉")
    assert t == {"first": "土", "second": "木", "third": "火"}, "取最旺的从神为第二/三用神"
    xi, ji, _ = _derive("土", direction="从势", gtype="cong_ruo", dm_wx="水")
    assert set([t["second"], t["third"]]) <= set(xi), "第二/三用神须落在喜神侧"
    assert not ({t["first"], t["second"], t["third"]} & set(ji)), "用神层次不得落在忌神侧"


