import pytest

from services.bazi.v2 import xiyong_v2

ALL_WX = {"木", "火", "土", "金", "水"}


def _derive(yong: str, *, direction: str = "扶抑", gtype: str = "zheng",
            dm_wx: str = "木"):
    """构造只含用神与方向的 `out`，直接调 `_derive_xi_ji`。"""
    out = {"theoretical": {"element": yong}, "practical": None, "direction": direction}
    return xiyong_v2._derive_xi_ji(out, dm_wx, gtype)


# ---------------------------------------------------------------
# 用神＝金/木/火/土/水 五种情形的 xi / ji（FR-035；书 下 3693 / 下 4265）
# ---------------------------------------------------------------

@pytest.mark.parametrize("yong,xi,ji", [
    # 用神=金：生金者土；克金者火；金克木（木生火＝生忌神者，同入忌）
    ("金", ["土"], ["木", "火"]),
    # 用神=木：生木者水；克木者金；木克土
    ("木", ["水"], ["土", "金"]),
    # 用神=火：生火者木（书 下 3693「木助火为喜神」）；克火者水（书 下 4265「水为忌神」）；火克金
    ("火", ["木"], ["金", "水"]),
    # 用神=土：生土者火；克土者木；土克水
    ("土", ["火"], ["水", "木"]),
    # 用神=水：生水者金；克水者土；水克火
    ("水", ["金"], ["火", "土"]),
])
def test_xi_ji_for_each_yongshen(yong, xi, ji):
    """喜神＝生用神者（下 3693）；忌神＝克用神者（下 4265）＋用神所克者。"""
    got_xi, got_ji, _ = _derive(yong)
    assert got_xi == xi, f"用神={yong} 的喜神应为 {xi}"
    assert got_ji == ji, f"用神={yong} 的忌神应为 {ji}"


def test_datamodel_section5_example_verbatim():
    """与 data-model §5 示例**逐字一致**：用神＝金 → xi ["土"]、ji ["木","火"]。

    修复前引擎给喜 ['水','火'] 忌 ['土','木']——正是 S1 报告的实跑值。
    """
    xi, ji, _ = _derive("金")
    assert xi == ["土"]
    assert ji == ["木", "火"]


def test_xian_shen_is_the_drainer_of_yong():
    """闲神＝泄用神者（用神所生者）。

    书 下 3390：甲木身旺时金、土皆为用神（「金是用神」「土为用神」），而丙火
    （甲木所生，泄用神）只须「适量，不能太旺」，未被列入忌神——故归闲神。
    > data-model §5 该处写 `"xian_shen": []`，是其示例的占位；金/木/火/水/土 五行
    > 按「生用神·用神·泄用神·克用神·用神克」恰好五分，泄用神者必落在闲神位。
    """
    xi, ji, xian = _derive("金")
    assert xian == ["水"], "金生水——水为泄用神者，归闲神"


def test_xi_ji_xian_partition_all_five_elements():
    """喜/忌/闲 ＋ 用神 必须**无重无漏**地覆盖五行（每个五行只有一个角色）。"""
    for yong in ALL_WX:
        xi, ji, xian = _derive(yong)
        roles = [yong, *xi, *ji, *xian]
        assert len(roles) == len(set(roles)) == 5, f"用神={yong} 的角色划分有重或有漏：{roles}"
        assert set(roles) == ALL_WX


