"""T021 · v2 通根递减测试（012 期 US2，FR-014 / FR-015）。

书源：《四柱精髓（上）》557-602（通根理论）；993-1008（通根计算）；
《四柱预测学入门》L667（远近递减表）。

远近递减（书 562-568）：
  ① 同柱通根力量完全，不用递减；
  ② 相邻通根减 0.5 度；③ 相隔通根减 1 度；④ 远隔通根减 2 度；
  ⑤ 不为同柱的通根，如果**中隔之支或中隔之干藏有其同类**则按最近的通根计；
  ⑥ 通根于月令者不按远近计，均按同柱论。
"""

import pytest

from services.bazi.v2 import degrees


def _chart(year, month, day, time):
    return {k: (None if v is None else {"gan": v[0], "zhi": v[1]})
            for k, v in (("year", year), ("month", month), ("day", day), ("time", time))}


def _cols(y, m, d, t):
    return degrees.build_cols({
        "year": {"gan": y[0], "zhi": y[1]},
        "month": {"gan": m[0], "zhi": m[1]},
        "day": {"gan": d[0], "zhi": d[1]},
        "time": {"gan": t[0], "zhi": t[1]},
    })


# ---------------------------------------------------------------
# 远近递减四档（书 562-566）
# ---------------------------------------------------------------

def test_same_pillar_root_no_penalty():
    """同柱通根力量完全，不用递减（书 563①）。

    乙卯 丙申 丁巳 戊午：乙（年干）通根年支卯（乙5）＝同柱，不减；
    月令申无木根，故不走「通根月令视同柱」的免罚路径。
    """
    c = _cols(("乙", "卯"), ("丙", "申"), ("丁", "巳"), ("戊", "午"))
    assert degrees.stem_tonggen(c, 0, "申") == 5.0


def test_adjacent_root_penalty_half():
    """相邻通根减 0.5 度（书 563②）。

    丙申 乙巳 丁卯 戊午：乙（月干）通根日支卯（乙5）＝相邻 → 5 - 0.5 = 4.5。
    月令必须取巳——若把卯放进月令会走「通根月令免罚」，验不出递减。
    """
    c = _cols(("丙", "申"), ("乙", "巳"), ("丁", "卯"), ("戊", "午"))
    assert degrees.stem_tonggen(c, 1, "巳") == 4.5


def test_separated_root_penalty_one():
    """相隔通根减 1 度（书 563③）。

    庚申 丙戌 癸未 壬午：癸（日干）通根年支申（壬2）＝相隔 → 2 - 1 = 1。
    时支取午（不含水）以隔离出年支申这一个根。
    """
    c = _cols(("庚", "申"), ("丙", "戌"), ("癸", "未"), ("壬", "午"))
    assert degrees.stem_tonggen(c, 2, "戌") == 1.0


def test_far_root_penalty_two():
    """远隔通根减 2 度（书 563④）。

    同盘：壬（时干）通根年支申（壬2）＝远隔 → 2 - 2 = 0（负值归 0）。
    """
    c = _cols(("庚", "申"), ("丙", "戌"), ("癸", "未"), ("壬", "午"))
    assert degrees.stem_tonggen(c, 3, "戌") == 0.0


# ---------------------------------------------------------------
# 中隔同类（书 563⑤）
# ---------------------------------------------------------------

def test_intervening_same_kind_shortens_distance():
    """中隔之干为同类时按最近通根论——同柱不减（书 588）。

    庚午 丙戌 癸未 壬子（书 583 例 1 的结构，年支改为午以隔离出水之根）：
    癸（日干）通根时支子（癸5）本应减 0.5，但中隔之干壬水为癸之同类
    （相当于癸挪到壬的位置上）→ 按同柱论，不减 = 5。
    """
    c = _cols(("庚", "午"), ("丙", "戌"), ("癸", "未"), ("壬", "子"))
    assert degrees.stem_tonggen(c, 2, "戌") == 5.0


# ---------------------------------------------------------------
# 通根月令视同柱（书 568⑥）
# ---------------------------------------------------------------

def test_root_in_month_pillar_is_never_penalized():
    """通根于月令者不按远近计，均按同柱论（书 568⑥）。

    癸巳 甲辰 丙午 戊戌：全局水只有 癸（年干）与 月支辰中的癸1度。
    癸（年干）到月支辰本为相邻（应减 0.5），但因辰是**月令** → 按同柱论 → 1.0。
    """
    c = _cols(("癸", "巳"), ("甲", "辰"), ("丙", "午"), ("戊", "戌"))
    assert degrees.stem_tonggen(c, 0, "戌") == 1.0, "通根月令按同柱论，1 度不减"


# ---------------------------------------------------------------
# 天干连片（书 562 / 上 651）
# ---------------------------------------------------------------

def test_adjacent_same_stems_combine():
    """相邻紧贴的同类天干可相加（FR-015；上 651「年干戊土不与日干相邻紧贴，所以天干只算2度」）。"""
    c = _cols(("戊", "申"), ("戊", "辰"), ("戊", "午"), ("壬", "子"))
    # 三戊相连 → 3 个天干
    assert degrees.stem_run_len(c, 0) == 3


def test_non_adjacent_same_stems_do_not_combine():
    """不相邻的同类天干分别独立计算（FR-015）。"""
    c = _cols(("戊", "申"), ("壬", "辰"), ("戊", "午"), ("庚", "子"))
    assert degrees.stem_run_len(c, 0) == 1, "年、日两戊不相邻（中隔壬），不得相加"
    assert degrees.stem_run_len(c, 2) == 1


# ---------------------------------------------------------------
# 连成一片（书 上 621）
# ---------------------------------------------------------------

def test_connected_run_penalized_once_by_nearest_branch():
    """连成一片的通根，按**最近的那一支**与天干的柱距递减一次（书 上 621）。

    书原文（乾 戊寅 乙丑 庚寅 己卯 财星木一节）：「日支寅和时支卯均藏有木而且它们是
    相邻紧贴的关系，我们称之为『连成一片』，连成一片者我们可以把它当成一个整体来看，
    即藏8度（寅+卯）木，而**日支与乙木相邻减去0.5度即8-0.5=7.5度**」。

    同例年支寅的 3 度与乙木相邻 → 2.5 度；故乙木在支的实际通根 = 2.5+7.5 = 10 度。

    > 原实现的 `pipeline._run_split` 把连片当成「不用递减」（返回 0），与书上式不符；
    > 2026-09-11 修正为与 `degrees.stem_tonggen` 同一口径（见 `test_v2_wangdu_cases`
    > 的 pipeline 断言）。
    """
    c = _cols(("戊", "寅"), ("乙", "丑"), ("庚", "寅"), ("己", "卯"))
    assert degrees.stem_tonggen(c, 1, "丑") == 10.0
    # 拆开看：年支单段 3−0.5=2.5；日+时连片段 8−0.5=7.5
    assert degrees.root_penalty(c, 1, 0, "木") == 0.5
    assert degrees.root_penalty(c, 1, 2, "木") == 0.5


def test_connected_run_same_pillar_not_penalized():
    """连片段最近一支为**同柱**时递减为 0（书 上 657「两申连成一片，按最近的通根——
    同柱通根论不用递减，总数为7度」）。"""
    c = _cols(("戊", "申"), ("庚", "申"), ("戊", "午"), ("戊", "午"))
    # 两申连成一段共 6 度，最近的通根为月支申（与月干庚同柱）→ 不减，合计 6 度
    assert degrees.stem_tonggen(c, 1, "申") == 6.0


# ---------------------------------------------------------------
# 负值归 0（FR-014）
# ---------------------------------------------------------------

def test_negative_result_clamped_to_zero():
    """递减后不足即为 0，不出现负值（FR-014）。"""
    c = _cols(("庚", "申"), ("丙", "戌"), ("癸", "未"), ("壬", "午"))
    assert degrees.stem_tonggen(c, 3, "戌") == 0.0
    assert degrees.stem_tonggen(c, 3, "戌") >= 0.0
