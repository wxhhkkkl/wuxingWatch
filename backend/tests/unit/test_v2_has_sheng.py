def test_book_case_xia_3858_is_cong_ruo():
    """书 下 3858（乾 乙未 丙戌 壬戌 庚戌，比尔·盖茨之造）书判**从弱**。

    > 书 下 3858：「壬水日元，**弱极，以从弱论**。壬水从弱，相当于壬水身旺，说明它
    > 是汹涌奔腾之水，必须要用厚重之土来『围水』或木来泄之方可显贵。」

    壬水动态 0.5 度、通根 0 度、**不受庚金之生**——庚金静态 0.5 度、无强根、无生，
    按书 上 982 无生克权，故**不能生水**（书 上 689「主生者必须具有生克权」）。
    三条俱足 → 不能独立 → 从弱（从神取最旺的土 30.3 度 = 官杀 → 从杀）。

    第一轮的 `_fed` 不查主生者，把「庚金生壬水」记成有生 → 日主「能独立」→ 误判
    **正格**（独立复核实测：394 书例中 31 例格局变化，书里明标从格的 15 例里
    14 例被改回正格，本条即其一）。
    """
    gj = _geju("壬", "乙未 丙戌 壬戌 庚戌")
    assert gj["type"] in CONG_RUO_FAMILY, gj["basis"]
    assert any("不能独立" in b for b in gj["basis"]), gj["basis"]


