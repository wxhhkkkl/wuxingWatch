PILLARS_982 = ("乙卯 戊子 己酉 丙寅", "己")     # 书 上 982 例1
PILLARS_984 = ("戊午 丙辰 甲辰 壬申", "甲")     # 书 上 984 例2


def test_shang_982_producer_without_power_cannot_feed():
    """书 上 982 例1（乾 乙卯 戊子 己酉 丙寅）：丙火无生克权 → **不能生己土**。

    > 书 上 982：「丙火静态旺度太弱（1.5度），无强根（1度），又无生（丙火不受寅木之
    > 生，虽有若无），所以**丙火没有生克权，丙火不能生日元己土**。」

    丙火（时干）与己土（日干）紧贴——只查受生方就会把土标成「有生」；按书 上 689
    「主生者必须具有生克权」，土实为**无生**。
    """
    r = pipeline.compute_strength(_pillars(PILLARS_982[0]))
    assert r["static_scores"]["火"] == 1.5, "书：丙火静态旺度 1.5 度"
    assert r["has_sheng"]["土"] is False, "丙火无生克权，不能生土"


def test_shang_984_producer_with_power_does_feed():
    """书 上 984 例2（乾 戊午 丙辰 甲辰 壬申）：壬水**有生克权** → 可以生日元甲木。

    > 书 上 984：「壬水有根无气，壬水静态旺度为2.5度，申金的静态旺度为7.5（5*1.5）度，
    > 申金是壬水的3倍，显然还是适量的生，故壬水可以接受申金的生。壬水静态旺度2.5度，
    > 又有生，虽然没有强根，但**壬水有生克权，壬水可以生日元甲木**。」

    反向对照（防「一刀切成全 False」）：壬水静态 2.5 度 ≥2.4 有生克权，且与甲木
    紧贴、在受生范围内 → 木**有生**。
    """
    r = pipeline.compute_strength(_pillars(PILLARS_984[0]))
    assert r["static_scores"]["水"] >= 2.4, "书：壬水静态旺度 2.5 度"
    assert r["has_sheng"]["木"] is True, "壬水有生克权，可以生日元甲木"


def test_has_sheng_for_day_master_is_about_the_day_pillar_itself():
    """日主的「有生」判在**日主自己那一柱**，不由同五行的旁干/旁支代劳。

    书 上 982 例1 的「丙火…又无生」是就**丙火这一干**说的。本例（乙巳 己卯 丙子 己丑）：
    年柱乙巳**同柱**乙木生巳火（书 上 1537「天干和地支之间只有同柱才能作用即论生克」），
    但那是**年支巳**受生，不是日主丙火受生；日柱丙子 的同柱对是**子水克丙火**（支克干），
    与「生」无关。若按五行取并集，日主就会白得年柱那一份「有生」，「不能独立」的
    第三项被旁支静默填真。
    """
    pillars = _pillars("乙巳 己卯 丙子 己丑")
    r = pipeline.compute_strength(pillars)
    # 年柱那一对确实在同柱对里（火受生），但受方是**年支巳**
    from services.bazi.v2 import degrees as _d
    sp = pipeline.same_pillar_pairs(_d.build_cols(pillars))
    assert ("木", "火") in sp, sp
    assert r["has_sheng"]["火"] is False, "日主丙火那一柱没有受生"
