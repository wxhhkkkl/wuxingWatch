"""岁运之干纳入天干五合（013 期 T020 / T026；FR-012 / FR-012a / FR-014a）。

**书的两条**：

1. **岁运之干与原局任何一柱的天干都相邻**（书 上 578「岁运的天干到原局任何一柱的天干
   的距离都是相同的，都是相邻的关系」），故可参与五合；
2. **但「中隔同类」对相合无效**（书 上 1745 / 1529）：岁运介入虽使原局相隔之干「变为相邻」，
   那只对**生克**有效——**对相合无效**。

书例 上 1745 例8（坤 己丑 辛未 甲戌 戊辰 + **己巳**运）把两条都说清了：

> 此造年日甲己合，坐支有土，而且当令，甲己合土似乎成功？但由于甲己**不相邻紧贴**，
> 故甲己合不成功……进入己巳运，**大运己土与日干甲己合化土**能否成功？此时甲己合相邻，
> 化神当令，坐支有土，甲己合**当然成功**。会不会出现 **2 己争合 1 甲**呢？**不会**，
> 年干己土虽然由于运干己土的介入而与日干变为相邻关系，但**对相合来说并不适用**，
> 即**年干是不能跟日主相合的，只有运干与日主相合**，所以运干与日相合成功。

**由此三条断言**：

| # | 断言 | 依据 |
|---|---|---|
| ① | 原局 年己 与 日甲 **不成合**（不相邻） | 上 1745 前半 |
| ② | 加己巳运后，**运干己 与 日干甲 合化土** | 上 1745 后半 |
| ③ | **不构成争合**（原局年己不得因运干介入而与日干相合） | 上 1745「对相合来说并不适用」；上 1529 |

> **T026 的难点不在候选生成，而在换字的跨层传播**：原局干被合化换字后，`cols[i].gan`
> 变了、由 `pipeline` 的「换字后重判地支」链路处理 ✓；但**岁运之干**不在 `cols` 里，
> 其换字须传到 `dayun.apply_dayun_delta` 的「运干同类 +1」判据上——那是另一个模块。
> 故本文件先钉住行为，实现见 T026。
"""

import pytest

from services.bazi.v2 import pipeline, relations


def _chart(*gz):
    return {k: {"gan": v[0], "zhi": v[1]} for k, v in zip(("year", "month", "day", "time"), gz)}


CHART = ("己丑", "辛未", "甲戌", "戊辰")          # 书 上 1745 例8


def _he_traces(r: dict) -> str:
    """取第 6 段（天干五合）的全部依据行，拼成一段文本。"""
    out: list[str] = []
    for st in r.get("steps") or []:
        if "天干五合" in str(st.get("title", "")):
            out.append(str(st))
    return " ".join(out)


# ---------------------------------------------------------------
# ① 原局：年己与日甲不相邻 → 不成合
# ---------------------------------------------------------------

def test_natal_year_ji_and_day_jia_are_not_adjacent():
    """书 上 1745 前半：「甲己**不相邻紧贴**，故甲己合不成功」。

    `己丑 辛未 甲戌 戊辰`：年己(0) 与 日甲(2) 之间隔着月辛 → 不相邻 → 五合候选都不产出。
    """
    r = pipeline.compute_strength(_chart(*CHART))
    assert r["day_master"] == "甲", "原局不成合，日干不换字"
    joined = _he_traces(r)
    assert "甲己" not in joined or "不成" in joined or "无" in joined, \
        "原局 年己·日甲 不相邻，不应判成合化：%s" % joined[:160]


# ---------------------------------------------------------------
# ② 加己巳运：运干己 与 日干甲 合化土
# ---------------------------------------------------------------

def test_dayun_gan_he_with_day_master():
    """书 上 1745 后半：「**大运己土与日干甲己合化土**……甲己合当然成功」。

    本断言在 T026 落地前**必然红**——`judge_stem_he` 的 `cols` 只含四柱，
    运干己根本进不了候选。
    """
    r = pipeline.compute_strength(_chart(*CHART), dayun_ganzhi="己巳")
    joined = _he_traces(r)
    assert "己巳" in joined or "运干" in joined or "_dayun" in joined, \
        "依据里应出现「运干己与日干甲」的合化结论（书 上 1745）：%s" % joined[:200]
    assert r["day_master"] == "戊", \
        "甲己合化土成功后日干换字为戊（书 上 1593 的换字口径）"
    assert "大运干己" in joined, "依据须标明该合涉及大运之干（书 上 1745）"


# ---------------------------------------------------------------
# ③ 不构成争合
# ---------------------------------------------------------------

def test_year_ji_does_not_join_the_zhenghe():
    """书 上 1745：「**不会**出现 2 己争合 1 甲……年干是不能跟日主相合的」。

    即：运干己 与 日干甲 成合之外，**原局年干己不得**也算作与日干相合（否则成 2:1 争合）。
    判据：依据里只应有**一条**甲己合，且其参与柱含 `_dayun`、不含 `year`。
    """
    r = pipeline.compute_strength(_chart(*CHART), dayun_ganzhi="己巳")
    sh = r.get("stem_he") or {}
    est = sh.get("established") or []
    jiaji = [e for e in est if e.get("pair") == "甲己"]
    assert jiaji, "应有甲己合（运干己与日干甲）：%s" % est
    for e in jiaji:
        cols = set(e.get("cols") or [])
        assert "_dayun" in cols, "该合的参与柱应含大运：%s" % cols
        assert "year" not in cols, \
            "年干己不得参与该合（书 上 1745「年干是不能跟日主相合的」）：%s" % cols
