"""T024 · v2 书例算式复核（012 期 US2，FR-017 / FR-023）。

从《四柱精髓（上）》第一节里挑出**书中给出完整算式**的命例，逐例复核静态旺度
与档位。这是 US2 从「机制正确」走向「书例正确」的关卡。

> **2026-09-11（T1）**：本文件的断言原先只打在 `degrees.static_scores` 上，
> 而生产路径走 `pipeline.compute_strength` 的 `static_scores`——两者在「连成一片」
> 的递减口径上曾经不一致（见 S6）。现在**普通盘同时校验两条路径的 `static_scores`**，
> 使书例复核真正覆盖用户看到的数。

覆盖的算式：
  ① 例 1 戊寅 乙丑 庚寅 己卯（书 616-633）—— 庚金 =(1+2)×1.5 = 4.5；火 =3×0.5 = 1.5；
     木 =(1+10)×0.7 = 7.7（连成一片按最近支递减一次，书 621）
  ② 例 2 戊申 庚申 戊午 戊午（书 645-661）—— 日干戊土 =(2+6)×0.8 = 6.4；金 =14；水 =6；火 =5.6
  ③ 例 4 乙卯 丁亥 壬戌 壬寅（书 753）—— 月令亥卯合化木，日干壬取平均系数 → 2.8
  ④ 例（书 891）壬子 癸丑 辛酉 己亥 —— 月令丑被化为金，金取平均 → 22.75
  ⑤ 例（书 883）辛酉 戊戌 丁卯 庚戌 —— 戌月火以**相**论、卯戌合绊火总量 +1 摊到两戌
     → 火 =(1+6+1−0.5)×1.5 = 11.25
"""

import pytest

from services.bazi.v2 import degrees, pipeline


def _pillars(y, m, d, t):
    return {
        "year": {"gan": y[0], "zhi": y[1]},
        "month": {"gan": m[0], "zhi": m[1]},
        "day": {"gan": d[0], "zhi": d[1]},
        "time": {"gan": t[0], "zhi": t[1]},
    }


def _cols(y, m, d, t):
    return degrees.build_cols(_pillars(y, m, d, t))


def _plain(y, m, d, t):
    """无关系介入的盘：degrees 与 pipeline 必须同值（两条路径的口径一致性）。"""
    p = _pillars(y, m, d, t)
    return degrees.static_scores(_cols(y, m, d, t)), pipeline.compute_strength(p)["static_scores"]


