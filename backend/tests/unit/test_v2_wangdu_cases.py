def test_case4_month_hua_average_ren_water():
    """日干壬水 =（天干 2 度 + 通根 0）× 平均系数 1.4 = 2.8 度。

    书 753：「天干2度，地支亥藏4度但亥卯合化成功水变为0，共2度。亥卯合化成木，
    日干在月令所处的状态就有两个：旺地（亥）和休地（木）。那么，日干的静态旺度
    就等于这二者的平均数――先计算处于旺地的度数＝2X2＝4度，再计算处于休地的
    度数＝2X0.8＝1.6度，最后取二者的平均值为2.8度…也可以先计算壬水在月令的
    平均系数，平均系数=（2+0.8）*0.5=1.4，日主的静态旺度=2*1.4=2.8度」。

    > **S2**：原实现把月令状态**直接替换**为化神状态（水系在木处→休，2×0.8＝1.6），
    > 与书上「取二者平均」不符；书 638 明写「如果月令被合化成其他五行，则该五行
    > 在月令所处的状态就有两个，那么其最后的旺度就等于这二者的平均值」。
    """
    prod = pipeline.compute_strength(_pillars(("乙", "卯"), ("丁", "亥"), ("壬", "戌"), ("壬", "寅")))
    assert prod["month_effective_wx"] == "木"
    # 本盘另有丁壬合绊（月干丁与日干壬相邻五合，化木条件③要求「一支为木、另一支为
    # 水或木」——丁坐亥水可以，壬坐戌土不行，故不化）。2026-09-12 起合绊减力进静态
    # 旺度：日干壬 −2 成 → 0.8 度，故水 =（0.8＋1）× 平均系数 1.4 = **2.52**。
    # 书 753 成文于第一节，未计天干五合（同 C26-19）。
    assert prod["static_scores"]["水"] == 2.52


