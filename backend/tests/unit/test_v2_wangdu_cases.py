def test_case1_day_master_geng():
    """庚金 = (天干 1 + 通根丑中辛 2) × 丑月相 1.5 = 4.5（较弱）。

    书 619：「在天干只有1个金旺度为1，地支丑中藏了一个中气金旺度为2——
    由于它们为月令通根故不用递减，两者相加等于3；金在丑月处相地…3x1.5=4.5」。

    **管线口径另有乙庚合绊**（月干乙与日干庚相邻五合、化金条件③不满足 → 合绊），
    庚 −2 成 → 0.8 度，金 =（0.8＋2）×1.5 = **4.2**。书 619 成文于第一节、
    未讲天干五合（同 C26-19）。
    """
    deg, prod = _plain(("戊", "寅"), ("乙", "丑"), ("庚", "寅"), ("己", "卯"))
    # `degrees.*` 是**未受天干五合影响**的下层参考实现（src 内无生产调用方），
    # 五合是 pipeline 的第 2 段，故两路径在本盘上按设计不同值。
    assert deg["金"] == 4.5
    assert prod["金"] == 4.2


def test_case1_fire_horse():
    """官星火 =(寅 2 + 寅 2 − 相隔 1)× 丑月死 0.5 = 1.5（太弱）。

    书 631：「天干无火，年支寅藏2度，日支寅藏2度，它们是相隔的关系，
    要减去1度，即 2+2-1=3度，在月令处死地，乘以0.5得1.5度」。
    """
    deg, prod = _plain(("戊", "寅"), ("乙", "丑"), ("庚", "寅"), ("己", "卯"))
    assert deg["火"] == 1.5
    assert prod["火"] == 1.5


def test_case1_wood_connected_run():
    """财星木 =(天干 1 + 实际通根 10)× 丑月囚 0.7 = 7.7（偏弱）。

    书 621：「年支寅藏3度与乙木相邻减去0.5度得2.5度…日支寅和时支卯…连成一片…
    即藏8度（寅+卯）木，而日支与乙木相邻减去0.5度即8-0.5=7.5度…
    那么乙木在地支的实际总通根数=2.5+7.5=10度。加上天干乙木本身1度，那共11度。
    因木生丑月属囚地，故木的最后旺度=11x0.7=7.7度」。

    > **S6**：`pipeline._static_scores` 曾经把连片当成「不用递减」→ 8.05 度；
    > 生产路径与 `degrees` 的 7.7 至此合一。
    """
    deg, prod = _plain(("戊", "寅"), ("乙", "丑"), ("庚", "寅"), ("己", "卯"))
    # 管线口径另有乙庚合绊（乙 −4 成 → 0.6 度）→ 木 =（0.6＋10）×0.7 = 7.42；
    # `degrees.*` 无五合层，仍按书 621 的 1 度干算 7.7。见同文件 `test_case1_day_master_geng`。
    assert deg["木"] == 7.7
    assert prod["木"] == 7.42


