def test_case2_day_master_wu():
    """日干戊土 = 其连片组(日/时两戊 2 + 通根 6)× 申月休 0.8 = 6.4（偏弱）。

    书 651：「天干有3个戊土似乎为3度，但年干戊土不与日干相邻紧贴，所以**天干只算2度**；
    地支两个午火各有一个中气的己土2度共4度，两申各藏1个余气的戊土共2度…
    总数＝2＋4＋2＝8度；在月令处于休地再乘以0.8，最后的旺度就是6.4度」。

    > 注意取的是**日主所在连片组**的度数，不是「土」的五行总和——
    > 书 653 明说「这 6.4 度就是日干戊土的静态旺度，同时也是时干戊土的」，
    > 而年干戊土因不紧贴须另算（书 655 得 5.6）。
    """
    from services.bazi.v2 import tables

    c = _cols(("戊", "申"), ("庚", "申"), ("戊", "午"), ("戊", "午"))
    group = degrees.stem_group_degree(c, 2, "申")
    assert group == 8.0, "日主连片组（日/时两戊）的 天干+通根 度数"
    assert round(group * tables.COEF["休"], 2) == 6.4
    # 生产路径的 `static_scores["土"]` 是**整个土五行**（年干 + 日时连片组）的合计，
    # 与 `degrees.static_scores` 同口径；日主单干值 6.4 由上面的连片组算式给出。
    deg, prod = _plain(("戊", "申"), ("庚", "申"), ("戊", "午"), ("戊", "午"))
    assert prod["土"] == deg["土"]


def test_case2_year_stem_wu_differs_from_day_master():
    """年干戊土不与日干紧贴 → 须另算：书 655 得 (1+6)×0.8 = 5.6。"""
