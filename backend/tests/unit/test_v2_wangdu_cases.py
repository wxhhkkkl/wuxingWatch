def test_case6_xu_month_fire_is_xiang():
    """日元丁火 =(天干 1 + 两戌含火 6 + 卯戌合绊 1 − 相邻通根 0.5)×戌月相 1.5 = **11.25**。

    书 883：「日元丁火1度，两戌含火6度，卯戌合绊火增力1度，平均每个戌土增力0.5度火，
    变为3.5度；日元通根于时支为相邻通根减0.5度，共7.5度，生于戌月乘以系数1.5，
    日主的静态旺度＝7.5X1.5＝11.25度，属于偏旺」。

    书 上 1062「②戌土没有受到辰冲或丑刑：火…以相论，金…以死论」。

    > 该值曾是三处缺陷的合成结果，现已全部修正：
    > ① 戌月系数取错档（原取需要辰冲/2丑刑1戌的 ③ 档，火休×0.8）；
    > ② 卯戌合绊的「火 +1 度」作用对象写作「戌中丁火」，而 `tables._SHU` 把戌的火
    >   记成丙 → `fx["gan"]` 过滤时被静默丢弃（书上 2808「…丁火增力1度」、下 3122
    >   「当戌中丁火≥3 度」均写「丁火」）；
    > ③ 该 +1 是**两戌的总量**（「平均每个戌土增力 0.5 度火」），原实现按支各加 1 度。
    """
    prod = pipeline.compute_strength(_pillars(("辛", "酉"), ("戊", "戌"), ("丁", "卯"), ("庚", "戌")))
    assert prod["static_scores"]["火"] == 11.25
    # 戌月金以死论（×0.5），不再是相（×1.5）
    from services.bazi.v2 import tables

    assert tables.month_state("金", "戌") == "死"


def test_case7_muku_chong_tu_12():
    """日主戊土 =（1＋1＋12）× 巳月相 1.5 = 21 度（比旺）。

    书 899：「日元1度，月令巳藏土2度但巳亥冲去掉1度土，**辰戌相冲成功含土12度**，
    生于巳月相地乘以系数1.5，日主的静态旺度＝（1＋1＋12）x1.5＝21度，属比旺」。

    > 跨工作流：墓库冲「成功 → 每支纯土 6 度」在 WS-C（S4）名下，本用例是它与
    > 月令系数（WS-B）的联合校验——若本用例转红，先看 `ban.py` 的墓库冲效果形状。
    """
    prod = pipeline.compute_strength(_pillars(("辛", "亥"), ("癸", "巳"), ("戊", "戌"), ("丙", "辰")))
    # 本盘月干癸与日干戊相邻五合且**戊癸化火成功**（上 2089 四条件全满足），日元戊
    # 换成丙，土的那 1 度随之消失：土 =（0＋1＋12）×1.5 = **19.5**。
    # 书 899 成文于第一节、未讲天干五合（同 C26-19，详见 `test_v2_ban.py` 同名用例）。
    assert prod["static_scores"]["土"] == 19.5


