"""天克地冲的**多支合并**、参与柱筛选与地支腿度数（013 期批 6a/6b）。

## 书的口径

- **什么是天克地冲**：书《入门》788「天克地冲：顾名思义，天克地冲就是**天干相克，
  地支相冲**」；答疑 216「天干**没有相冲**，天干只有同性相克和异性相克」。
  故 `GAN_CHONG` 是**天干相克**表，2026-09-28 由四组扩到**有书例的八组**。
- **多支算一条**：下 3264「**2个癸亥与1个丁巳**天克地冲」、下 1992「**1亥与2巳**
  （时柱巳也加入）」、下 1786「**1辰冲2戌**均成功」、下 1693「1酉冲**2卯**」。
- **级位**：下 3186 的顺序表里天克地冲（2）**高于**六冲（8），两者并见时论天克地冲。
- **合解冲不适用于天克地冲**（2026-09-28 用户裁定）：下 3265「先论天克地冲，天克地冲
  出现，**亥卯、巳酉合绊、三亥自刑就不能成功**」；下 1278「丑未冲为天克地冲，
  **天克地冲具有优先权**」。而下 1979 例1 的六冲**可以**被 tier 13 的合解掉
  ——两条形状相同、结论相反，差别只在冲的级位。下 1974 括注「须同时合住两支
  **或逢天合地合**」里能成立的那条合只有天合地合（tier 1，高于天克地冲）。
- **地支腿度数 = 普通六冲**：答疑 1106「天克地冲，**其实质还是冲**」；三处带度数的算例
  （下 1786/1810/1843）全部照搬六冲。**天干腿不在此施加**（属静态旺度体系，会与
  pipeline 的天干生克重复计）。
- **参与柱**：边＝`_tkc_act`——中隔的**每一支**都须是两端之一。下 3264 的 月亥/时巳
  中隔 日亥（同类）→ 参与；下 1655 的年午/时子 中隔 寅（非同类）→「**年时子午不冲**」。
- **三刑优先**：下 2131「寅申既是相冲又是相刑，当它们单独出现时我们论冲不论刑；
  **当它们与巳火一起出现时，我们论刑不论冲**」——故寅申之冲落在三刑内时不先成立。
"""

import pytest

from services.bazi.v2 import relations

KEYS4 = ("year", "month", "day", "time")


def _chart(*gz4):
    return {k: {"gan": g[0], "zhi": g[1]} for k, g in zip(KEYS4, gz4)}


def _with(dayun, liunian, *gz4):
    c = _chart(*gz4)
    c["_dayun"] = {"gan": dayun[0], "zhi": dayun[1]}
    if liunian:
        c["_liunian"] = {"gan": liunian[0], "zhi": liunian[1]}
    return c


def _t2(r, zhis=("寅", "申")):
    return next((e for e in r["established"]
                 if e["tier"] == 2 and set(e["members"][-2:]) == set(zhis)), None)


def _rej_all(r):
    return [(e["tier"], e["type"], e["cols"]) for e in r["rejected"]]


def _fx(e, zhi, gan):
    return next((f for f in e["effects"]
                 if f["zhi"] == zhi and f.get("gan") == gan), None)


