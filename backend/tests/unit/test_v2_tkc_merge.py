# 「中隔同类」例外的作用域：**相隔**可升格，**远隔**不可（批 A4）
# ---------------------------------------------------------------

def _adj(*gy):
    """按给的 (干, 支) 序列造 `_Col`，直接问 `_adjacent`。"""
    from services.bazi.v2 import relations as R

    class _C:
        def __init__(self, k, g, z):
            self.key, self.gan, self.zhi = k, g, z

    cols = [_C("p%d" % i, g, z) for i, (g, z) in enumerate(gy)]
    st = R._State(cols)
    return R._adjacent(st, cols[0], cols[-1])


def test_adjacent_exception_only_upgrades_相隔_not_远隔():
    """书 上 1533：「不相邻不作用，但如果**中隔的地支是它们其中的一个**则可作用」——措辞单数。

    四条互相独立的书证夹死这一点（形状都是「**远隔**：两端为年—时、中隔 2 支、
    恰有一支等于两端之一」），书一律判**不作用**：

    | 书证 | 柱对 | 中隔 |
    |---|---|---|
    | 下 1655 | 年午↔时子（六冲） | 月寅、**日午** |
    | 下 1011 | 年辰↔时子（子辰合） | 月**子**、日巳 |
    | 下 1015 | 年子↔时辰（子辰合） | 月酉、**日子** |
    | 下 2650 | 年辰↔时辰（辰辰自刑） | 月寅、**日辰** |

    而**唯一算例**是 上 1547-1548：「月时卯酉不相邻本来是不能相冲的，但**中隔酉金**，
    所以月时卯酉可以相冲」——那是**相隔（1 支中隔）**。
    """
    # 相隔（1 支中隔）同类 → 可作用（上 1548：月卯·**日酉**·时酉，取卯与末酉为两端）
    assert _adj(("乙", "卯"), ("癸", "酉"), ("辛", "酉")), \
        "中隔之支为酉（同类）→ 可作用（上 1548）"
    # 相隔但中隔非同类 → 不作用（上 1548 的反例：癸酉换成壬申）
    assert not _adj(("乙", "卯"), ("壬", "申"), ("辛", "酉"))
    # 远隔（2 支中隔）且恰有一支同类 → **不**作用（下 1655 同形：年午·月寅·日午·时子）
    assert not _adj(("戊", "午"), ("甲", "寅"), ("戊", "午"), ("壬", "子")), \
        "中隔 寅、日午 → 远隔不作用（下 1655）"
    # 远隔但**每一支**中隔都是两端之一 → 作用（`all` 的边界；书无此类算例）
    assert _adj(("甲", "卯"), ("甲", "卯"), ("甲", "戌"), ("甲", "戌"))
