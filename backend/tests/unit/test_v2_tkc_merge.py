def test_xia3264_two_guihai_one_dingsi_is_one_relation():
    """下 3264 乾 癸卯 癸亥 癸亥 丁巳（原局）。

    书：「先论天克地冲——**2个癸亥与1个丁巳**天克地冲，巳亥冲，癸克丁，
    **巳亥冲之后，就不能再论亥卯合与亥亥自刑了**」。

    旧实现按 `_pairs` 逐对产出，月-时那条被日-时挤掉；且「两亥自刑」曾被收窄守卫
    判成成立（cols 只剩月亥）——两条一并修掉。
    """
    r = relations.judge_relations(_chart("癸卯", "癸亥", "癸亥", "丁巳"))
    e = _t2(r, ("亥", "巳"))
    assert e is not None, "应判出天克地冲（书 下 3264）"
    assert set(e["cols"]) == {"month", "day", "time"}, \
        "2个癸亥与1个丁巳并成一条（月亥经中隔同类并入）：%s" % e["cols"]
    assert not [x for x in r["established"] if x["tier"] == 14], \
        "亥亥自刑不得成立（书「不能再论…亥亥自刑」）"
    assert not [x for x in r["established"] if x["tier"] in (10, 12)], \
        "亥卯合不得成立（书「不能再论亥卯合」）"


def test_xia3265_xinyou_the_book_conclusion_verbatim():
    """下 3265 同盘 + 辛酉运。

    书：「先论天克地冲，天克地冲出现，**亥卯、巳酉合绊、三亥自刑就不能成功**，
    所以最后论巳亥天克地冲、**卯酉冲**，不论巳酉合绊、亥卯合绊、亥亥自刑」。

    这是「合解冲不适用于天克地冲」的直接书证——旧实现让 tier 10/13 的合反手
    解掉了 tier 2 的天克地冲，把因果关系整个倒了过来。
    """
    r = relations.judge_relations(_with("辛酉", None, "癸卯", "癸亥", "癸亥", "丁巳"))
    assert _t2(r, ("亥", "巳")) is not None, "巳亥天克地冲成立（书 下 3265）"
    assert [x for x in r["established"] if x["tier"] == 8], "卯酉冲成立（书 下 3265）"
    assert not [x for x in r["established"] if x["tier"] == 14], "亥亥自刑不成立"
    assert not [x for x in r["established"] if x["tier"] in (10, 13)], \
        "亥卯半合、巳酉合绊均不成立"


