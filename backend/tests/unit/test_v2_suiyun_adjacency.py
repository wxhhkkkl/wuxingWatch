"""岁运支的**相邻性、桥接与让位**（013 期 T008；FR-005~008）。

## 书的口径

**上 578**：「岁运的天干到原局**任何一柱**的天干的距离都是相同的，都是相邻的关系；
岁运的地支到原局任何一柱的地支的距离都是相同的，都是相邻的关系。」
——故「相隔不作用」（上 1533「不相邻不作用」）**不适用于岁运支与原局支之间**。

**上 1541**：「原局不相邻的天干与天干、地支与地支不作用，但是**如果岁运有它们的同类或
它们本身介入则变成作用**。」

**桥接**（岁运使原局相隔之支变为可作用）的算例：上 1557、下 1684、上 2203、上 2944、上 3502。

**让位**同样适用于岁运支（下 3173「运支戌不参与相害和半会」、下 3286 运支子让位）。

## 现状（写测试时的实测）

| 例 | 书判 | 引擎现状 |
|---|---|---|
| 上 3502 乙卯 戊寅 丁未 辛亥 + 乙亥运 | 亥卯未变相邻 → **合化木成功** | **不成**（只有 `亥亥自刑`，cols=`['time','_dayun']`）→ **红** |
| 乙卯 丁未 甲子 丙申 + 己亥运 | 运亥与年卯/月未同局 → 三合成 | **不成** → **红** |
| 下 3286 丙戌 乙未 癸卯 己未 + 庚子运 | 运子让位，只论卯未合绊 | **一致** → 守卫 |
| 下 3173 癸酉 辛酉 己酉 甲戌 + 壬戌运 | 运戌不参与相害和半会 | **一致**（酉s 被自刑占用，戌 进不了） → 守卫 |

> **`亥亥自刑` 那条 cols=`['time','_dayun']` 是「下标巧合」的直接实证**：伪列追加在列尾
> （`_EXTRA_ORDER`），`_ju_runs` 按下标算连续段，于是运支只与**时支**算紧贴、与年支不算。
> 书 上 578 要的是「与任何一柱都相邻」——故 T013 改的是**语义**，不是补一个 `if`。
"""

import pytest

from services.bazi.v2 import relations


def _chart(*gz):
    return {k: {"gan": v[0], "zhi": v[1]} for k, v in zip(("year", "month", "day", "time"), gz)}


def _with_dayun(gz: str, *gz4):
    c = _chart(*gz4)
    c["_dayun"] = {"gan": gz[0], "zhi": gz[1]}
    return c


def _ju(r, tier, members):
    for e in r["established"]:
        if e["tier"] == tier and set(e["members"]) == set(members):
            return e
    return None


# ---------------------------------------------------------------
# 桥接（FR-007）——两处，写时全红
# ---------------------------------------------------------------

def test_bridge_book_case_shang_3502():
    """书 上 3502 乙卯 戊寅 丁未 辛亥。

    书：「原局亥卯未合，只有亥未相邻，**卯并不相邻**，第一个条件不满足，则亥卯未合不成……
    进入乙亥运，**大运亥介入，使得亥卯未变得相邻紧贴**，满足了第一个条件；……故亥卯未
    合化木成功，多出一支亥也加入合局并论化。」
    """
    r = relations.judge_relations(_with_dayun("乙亥", "乙卯", "戊寅", "丁未", "辛亥"))
    san = _ju(r, 6, ["亥", "卯", "未"])
    assert san is not None, (
        "运支亥介入后，亥卯未应成立（书 上 3502）；"
        "若此处为 None，说明 `_ju_runs` 仍按列尾下标算连续段、未实现桥接")
    assert san["hua"] == "木", "书：亥卯未**合化木成功**"
    assert "_dayun" in san["cols"], "该局必须含运支亥（书：「多出一支亥也加入合局」）"


def test_bridge_dayun_joins_a_ju_with_distant_natal_branches():
    """书 上 578 的相邻语义：运支与**年支**同属一局时也须成局。

    `乙卯 丁未 甲子 丙申` + `己亥`运：年卯（下标 0）与月未（下标 1）相邻，
    运亥在下标 4——按现实现（下标算距离）亥既不与 0 相邻也不与 1 相邻，故不成局；
    按书 上 578「与任何一柱都相邻」，亥卯未三合木应成立。
    """
    r = relations.judge_relations(_with_dayun("己亥", "乙卯", "丁未", "甲子", "丙申"))
    assert _ju(r, 6, ["亥", "卯", "未"]) is not None, \
        "运支亥应与年卯、月未共同成局（书 上 578：岁运到任何一柱均相邻）"


# ---------------------------------------------------------------
# 让位适用于岁运支（FR-006）——两处守卫，现已与书一致
# ---------------------------------------------------------------

def test_dayun_holds_no_relation_when_natal_ju_consumes_it():
    """书 下 3286 丙戌 乙未 癸卯 己未 + 庚子运。

    书：「进入庚子运，出现了未戌刑、卯未合绊、子未相害、子卯刑，先论卯未合——卯未合
    不成功，再论未戌刑、子卯刑，但未戌刑、子卯刑也不成功；最后论子未相害，**子未相害
    要让位给卯未合绊**。所以最后只能论卯未合绊，不再论未戌刑、子卯刑、子未害。」

    断言：运支子**不出现在任何成立关系的参与柱里**。
    """
    r = relations.judge_relations(_with_dayun("庚子", "丙戌", "乙未", "癸卯", "己未"))
    assert _ju(r, 13, ["卯", "未"]) is not None, "卯未合绊应成立（书：最后只能论卯未合绊）"
    holders = [e for e in r["established"] if "_dayun" in (e.get("cols") or [])]
    assert not holders, "运支子应让位（书 下 3286），却出现在：%s" % \
        [(e["tier"], e["members"]) for e in holders]


def test_dayun_holds_no_relation_when_natal_relation_has_priority():
    """书 下 3173 癸酉 辛酉 己酉 甲戌 + 壬戌运。

    书：「进入壬戌运，运支戌土含火 3 度，运支戌土与酉金论相害，不论半会，由于原局酉戌
    半会成功，而**相害要让位给半会**，所以原局论半会成功，**运支戌不参与相害和半会**。」
    """
    r = relations.judge_relations(_with_dayun("壬戌", "癸酉", "辛酉", "己酉", "甲戌"))
    holders = [e for e in r["established"] if "_dayun" in (e.get("cols") or [])]
    assert not holders, "运支戌应不参与任何关系（书 下 3173），却出现在：%s" % \
        [(e["tier"], e["members"]) for e in holders]


# ---------------------------------------------------------------
# 无岁运时不受影响（守 FR-023）
# ---------------------------------------------------------------

def test_bridge_logic_is_inert_without_dayun():
    """上 3502 的**原局**应仍不成局（书：「卯并不相邻，第一个条件不满足」）。

    桥接是**岁运介入**的效果，不得让原局自己「变相邻」。
    """
    r = relations.judge_relations(_chart("乙卯", "戊寅", "丁未", "辛亥"))
    assert _ju(r, 6, ["亥", "卯", "未"]) is None, \
        "无大运时，原局的亥卯未不得成局（卯不相邻，书 上 3502）"
