"""四墓库**岁运度数档**的表级测试（013 期 T006；书 上 399-403 / 449-451 / 491-497）。

书对四个墓库的 ④ 档用了**两种写法**，不可一视同仁：

| 支 | 书证 | 写法 | 是否为月份条件 |
|---|---|---|---|
| 丑 | 上 399-403 ④ | 「当丑在**大运**出现时——含水2辛2己3；丑在**流年**或流日出现时——含水1辛2己3」 | **独立档**（与生于何月无关） |
| 辰 | 上 449-451 ④ | 「当辰在大运**或流年**、流日出现时：含水1乙2戊3」 | **独立档**（两档**相同**） |
| 未 | 上 490 / 492 | 「未土临**大运**：未土含火3度，含土3度」「未土临**流年**或流日：未土含火2度，含土3度，含木1度」 | **独立档**（与生于何月无关） |
| 戌 | 上 496 / 497 | 「戌土临**大运**：戌含火3度，含土3度」「戌土临**流年**或流日：戌土含土3度，含金2度，含火1度」 | **独立档**（与生于何月无关） |

**订正前三处与书不符**（012 期该三处无调用方，故订正零回归）：

1. 丑**没有流年档**——靠落到 `_CHOU_OTHER` 恰好取到对的值，但当月令为亥子月/申酉丑月时
   会被前面的分组分支截走，取到 ① 或 ② 的值；
2. 辰**两条岁运档都没有**——同病；
3. **戌的守卫误用 `hot`（巳午未月）**，且流年档**完全没有守卫**——书把它写在**戌月**块内。

**订正点 4（2026-09-24）：未/戌 的岁运档同**样**是独立档，不是月份条件。**

书对**四个**墓库的 ④ 档用的是**同一句式**——「当丑在**大运**出现时」「当辰在**大运或流年**、
流日出现时」「未土临**大运**」「戌土临**大运**」——全是**位置条件**，没有一个带月份限定。
旧实现把「书里的**排版位置**」读成了「适用条件」（未的写在「未戌生于巳午未月」块后、
戌的写在「未戌生于戌月」块后），于是嵌进了 `group == "hot"` / `group == "xu"` 守卫。

> **决定性书证（就在 013 的 fixture 集内）**：上 537（`jingsui-shang-0005`）
> 乾 **癸亥 辛酉 庚戌 甲申** + **己未**运——月令是**酉**（申酉月），书仍写
> 「进入己未运，未土临大运，未土含**火3度，含土3度**，不再含有其他五行」。
> 申酉月下 未 的原局档是 [己3 丁2 乙1]，而书给的是 [丁3 己3] ⇒ **与月令无关**。
> 该例早已在 `fixtures/suiyun-cases.json` 里，但 `compare_suiyun.py` **只对档位/格局/用神**，
> 藏干度数不在比对面内，故一直没被回归抓到。

**为何旧断言能通过**：戌@**戌月** 的岁运档引用的是 `_SHU["xu"]`（`tables.py:244`），
而 `_SHU["xu"]` **同时**是戌月原局档（经 `tables.py:245` 兜底可达）——**同一个常量**，
故「对上书值」是巧合；其余月令一律穿透到原局档。

> 本文件的断言**只测表**（`tables.hidden_degrees`），不测调用侧——「谁在什么情形下传
> `is_dayun`/`is_liunian`」是 T024 的职责（见 tasks.md 对 T006/T024 的切分）。
"""

import pytest

from services.bazi.v2 import tables

SUIYUN_ARGS = ("亥", "子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌")


def _tu(zhi: str, month: str, **kw) -> list[tuple[str, float]]:
    return tables.hidden_degrees(zhi, month, **kw)


# ---------------------------------------------------------------
# 丑（上 399-403 ④，独立档）
# ---------------------------------------------------------------

def test_chou_suiyun_tiers_differ_between_dayun_and_liunian():
    """丑：大运档 [癸2 辛2 己3]、流年档 [癸1 辛2 己3]——**两档不同**。"""
    assert _tu("丑", "寅", is_dayun=True) == [("癸", 2.0), ("辛", 2.0), ("己", 3.0)]
    assert _tu("丑", "寅", is_liunian=True) == [("癸", 1.0), ("辛", 2.0), ("己", 3.0)]


@pytest.mark.parametrize("month", SUIYUN_ARGS)
def test_chou_suiyun_tier_is_independent_of_month(month):
    """丑的岁运档是**独立档**——不因生于亥子月（①档 己0）或申酉丑月（②档）而改变。

    这正是订正点 1：订正前，`is_liunian` 在亥子月会取到 ① 档 [癸3 辛2 己0]。
    """
    assert _tu("丑", month, is_liunian=True) == [("癸", 1.0), ("辛", 2.0), ("己", 3.0)], \
        "%s 月：丑临流年应取 ④ 档，与月令无关" % month
    assert _tu("丑", month, is_dayun=True) == [("癸", 2.0), ("辛", 2.0), ("己", 3.0)], \
        "%s 月：丑临大运应取 ④ 档，与月令无关" % month


def test_chou_natal_tiers_unchanged():
    """**未传岁运标志时**，①②③ 档照旧——守「订正不影响既有口径」。"""
    assert _tu("丑", "子") == [("癸", 3.0), ("辛", 2.0), ("己", 0.0)]          # ①亥子月
    assert _tu("丑", "子", dangzhong=3) == [("癸", 2.0), ("辛", 2.0), ("己", 3.0)]
    assert _tu("丑", "申") == [("癸", 2.0), ("辛", 2.0), ("己", 3.0)]          # ②申酉丑月
    assert _tu("丑", "寅") == [("癸", 1.0), ("辛", 2.0), ("己", 3.0)]          # ③其他月


# ---------------------------------------------------------------
# 辰（上 449-451 ④，独立档、两档相同）
# ---------------------------------------------------------------

@pytest.mark.parametrize("month", SUIYUN_ARGS)
def test_chen_suiyun_tiers_are_identical_and_month_independent(month):
    """辰：大运档与流年档**相同**（均 [癸1 乙2 戊3]），且与月令无关。

    订正点 2：订正前辰**两条岁运档都没有**，亥子月会取到 ① 档 [癸3 乙2 戊0]。
    """
    want = [("癸", 1.0), ("乙", 2.0), ("戊", 3.0)]
    assert _tu("辰", month, is_dayun=True) == want, "%s 月：辰临大运应取 ④ 档" % month
    assert _tu("辰", month, is_liunian=True) == want, "%s 月：辰临流年应取 ④ 档" % month


def test_chen_natal_tiers_unchanged():
    assert _tu("辰", "子") == [("癸", 3.0), ("乙", 2.0), ("戊", 0.0)]          # ①亥子月
    assert _tu("辰", "申") == [("癸", 2.0), ("乙", 2.0), ("戊", 3.0)]          # ②
    assert _tu("辰", "寅") == [("癸", 1.0), ("乙", 2.0), ("戊", 3.0)]          # ③


