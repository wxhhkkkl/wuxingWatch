# 未（上 490 / 492，独立档）—— 订正点 4
# ---------------------------------------------------------------

@pytest.mark.parametrize("month", SUIYUN_ARGS)
def test_wei_suiyun_tier_is_independent_of_month(month):
    """未的岁运档是**独立档**——不因生于巳午未月（①档 丁4 己2）或申酉月而改变。

    书 上 490「未土临大运：未土含火3度，含土3度，不再含有其他杂气」、
    上 492「未土临流年或流日：未土含火2度，含土3度，含木1度」——**位置条件**，无月份限定。
    """
    assert _tu("未", month, is_dayun=True) == [("丁", 3.0), ("己", 3.0)], \
        "%s 月：未临大运应取 ④ 档，与月令无关" % month
    assert _tu("未", month, is_liunian=True) == [("丁", 2.0), ("己", 3.0), ("乙", 1.0)], \
        "%s 月：未临流年应取 ④ 档，与月令无关" % month


def test_wei_suiyun_tier_book_case_shang_537():
    """**书例锚（订正点 4 的决定性书证）**：上 537 乾 癸亥 辛酉 庚戌 甲申 + 己未运。

    月令是 **酉**（申酉月），未生于申酉月的原局档是 [己3 丁2 乙1]；而书明写
    「未土临大运，未土含**火3度，含土3度**，不再含有其他五行」——与月令无关。
    该例已在 `fixtures/suiyun-cases.json`（`jingsui-shang-0005`），但对拍只覆盖
    档位/格局/用神，藏干度数不在比对面内。
    """
    assert _tu("未", "酉", is_dayun=True) == [("丁", 3.0), ("己", 3.0)]
    # 原局档不动（守零回归）：未生于申酉月仍是 [己3 丁2 乙1]
    assert _tu("未", "酉") == [("己", 3.0), ("丁", 2.0), ("乙", 1.0)]


def test_wei_natal_tiers_unchanged():
    """**未传岁运标志时**，①②③ 档照旧——守「订正不影响既有口径」。"""
    assert _tu("未", "巳") == [("丁", 4.0), ("己", 2.0)]          # 巳午未月
    assert _tu("未", "酉") == [("己", 3.0), ("丁", 2.0), ("乙", 1.0)]  # 申酉月
    assert _tu("未", "戌") == [("丁", 3.0), ("己", 3.0)]          # 戌月
    assert _tu("未", "辰") == [("己", 3.0), ("乙", 2.0), ("丁", 1.0)]  # 辰月


